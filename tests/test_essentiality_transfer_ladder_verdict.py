def test_all_five_limits_are_literally_in_the_TEMPLATE_file():
    """In the template, not generated by code -- that is what makes them unomittable."""
    tpl = TEMPLATE.read_text(encoding="utf-8")
    for h in run.HONEST_LIMIT_HEADINGS:
        assert h in tpl, h


@pytest.mark.parametrize("verdict", tl.VERDICTS)
def test_every_verdict_renders_and_keeps_all_five_limits(verdict):
    rungs = [_rung("ecoli", 8, 0.31), _rung("paeruginosa", 5, 0.29), _rung("human", 1, 0.16)]
    out = run.render_memo(_art(rungs, verdict))
    for h in run.HONEST_LIMIT_HEADINGS:
        assert h in out, (verdict, h)
    assert verdict in out


def test_the_memo_refuses_cross_rung_auroc_and_sens_spec_comparison():
    """A string-level refusal check on the RENDERED output, because this is the comparison the
    different sampling frames make invalid (BAGEL curated extremes 0.431 vs genome-wide 0.0928)."""
    rungs = [_rung("ecoli", 8, 0.31), _rung("paeruginosa", 5, 0.29), _rung("human", 1, 0.16)]
    out = run.render_memo(_art(rungs))
    # no per-rung AUROC column, and no sens/spec columns at all
    table = out[out.index("## Per-rung table"):out.index("## Distance classes")]
    for banned in ("auroc", "sens", "spec", "precision"):
        assert banned not in table.lower(), f"{banned!r} must not appear in the per-rung table"
    # the refusal itself must be stated
    assert "No cross-rung AUROC or sens/spec\ncomparison appears in this document." in out \
        or "No cross-rung AUROC or sens/spec comparison appears in this document." in out.replace("\n", " ")


def test_the_memo_states_the_phrasing_floor_is_a_FLOOR():
    out = run.render_memo(_art([_rung("ecoli", 8, 0.31), _rung("human", 1, 0.16)]))
    assert "**FLOOR**" in out
    assert "under-corrects" in out
    assert "0.2491" in out and "0.1007" in out


