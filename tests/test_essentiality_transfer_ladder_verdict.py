"""Guards for the memo render — the honest limits must be unomittable and the refusals must hold."""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import essentiality_transfer_ladder as run  # noqa: E402

from dna_decode.eval import transfer_ladder as tl  # noqa: E402

TEMPLATE = ROOT / "wiki" / "essentiality_transfer_ladder_memo_template.md"


def _rung(key, depth, lift, adj=None, scored=True, wall=None):
    if not scored:
        return {"key": key, "organism": "X", "depth": depth, "technology": "transposon_insertion",
                "scored": False, "wall": wall or "WALL_SCHEMA_UNVERIFIED"}
    return {"key": key, "organism": "X", "depth": depth, "technology": "transposon_insertion",
            "scored": True, "coverage_essential": 0.4, "coverage_nonessential": 0.4 - lift,
            "coverage_lift": lift, "coverage_lift_adjusted": adj if adj is not None else lift + 0.01,
            "null_p95": 0.02, "null_max": 0.03}


def _art(rungs, verdict="SMOOTH_DECAY_WITH_DISTANCE"):
    return {"date": "2026-10-06", "primary_test": tl.PRIMARY_TEST,
            "frozen_thresholds": run.FROZEN_THRESHOLDS,
            "threshold_derivation": run.THRESHOLD_DERIVATION,
            "reconciled": {"ecoli": {"coverage_lift": 0.3125, "auroc": 0.6952},
                           "human": {"coverage_lift": 0.1633, "auroc": 0.5805}},
            "distance_classes": [{"depth": d, "rungs": k} for d, k in tl.distance_classes()],
            "rungs": rungs, "verdict": {"verdict": verdict, "reason": "r", "n_scored": 3, "detail": {}},
            "n_scored": sum(1 for r in rungs if r.get("scored")),
            "n_walled": sum(1 for r in rungs if not r.get("scored"))}


