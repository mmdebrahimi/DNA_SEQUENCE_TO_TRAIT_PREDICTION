def test_verdict_and_any_post_hoc_reading_occupy_DISTINCT_keys():
    """A post-hoc reading must never overwrite the mechanical output of the frozen bar."""
    art = _art([_rung("ecoli", 8, 0.31), _rung("human", 1, 0.16)])
    assert "verdict" in art and isinstance(art["verdict"], dict)
    assert "verdict" in art["verdict"]
    # the runner never writes a sibling that could be mistaken for the verdict
    src = (ROOT / "scripts" / "essentiality_transfer_ladder.py").read_text(encoding="utf-8")
    assert '"verdict": v.as_dict()' in src


def test_the_rendered_memo_has_no_unfilled_placeholders():
    out = run.render_memo(_art([_rung("ecoli", 8, 0.31), _rung("human", 1, 0.16)]))
    leftovers = re.findall(r"\{[a-z_]+\}", out)
    assert not leftovers, leftovers


