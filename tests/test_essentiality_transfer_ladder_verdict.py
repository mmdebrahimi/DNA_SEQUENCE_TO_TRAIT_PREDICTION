def test_the_primary_verdict_uses_ONLY_the_bacterial_subladder():
    """Technology held constant is the whole point of the primary test."""
    rungs = [_rung("ecoli", 8, 0.31), _rung("paeruginosa", 5, 0.30), _rung("saureus", 2, 0.29),
             _rung("scerevisiae", 1, 0.10), _rung("human", 1, 0.11)]
    prim = run.bacterial_subladder_verdict(rungs, **run.FROZEN_THRESHOLDS)
    assert prim.n_scored == 3, "only the three bacterial rungs"
    assert prim.verdict == tl.NO_DECAY_DISTANCE_INSENSITIVE
    # the full ladder over the same records sees the eukaryote drop and says CLIFF
    full = tl.classify_ladder(rungs, **run.FROZEN_THRESHOLDS)
    assert full.verdict == tl.DOMAIN_CLIFF
    assert prim.verdict != full.verdict, "primary and secondary must be able to disagree"


def test_the_secondary_is_labelled_confounded_in_the_output():
    out = run.render_memo(_art([_rung("ecoli", 8, 0.31), _rung("human", 1, 0.16)]))
    assert "technology-confounded AND sampling-frame-confounded" in out


def test_bar_sensitivity_is_reachable_from_a_constructed_case():
    """The vocabulary-probe lesson encoded: when the phrasing subtraction moves a rung into a different
    band, the instrument is not deciding and the memo must say so."""
    rungs = [_rung("ecoli", 8, 0.31, adj=0.32), _rung("paeruginosa", 5, 0.30, adj=0.31),
             _rung("human", 1, 0.16, adj=0.30)]        # raw low, adjusted high
    v = tl.classify_ladder(rungs, **run.FROZEN_THRESHOLDS)
    assert v.verdict == tl.INDETERMINATE_BAR_SENSITIVE
    out = run.render_memo(_art(rungs, v.verdict))
    assert tl.INDETERMINATE_BAR_SENSITIVE in out


