"""Semantic staleness auditor -- does a reasoning LLM beat the mechanical screen that failed?

THE QUESTION, NARROWLY. `tests/test_claude_md_citations.py` can check that a cited FILE EXISTS. It cannot
check that the file still SAYS what the claim says -- its own docstring records that the ProSST case would
not have been caught there. A mechanical proximity screen for that gap was built, scored 0/5 TP and 5/5 FP
on the benchmark, and was deliberately not shipped. **Does a semantic model do better?** That is the only
question here, and `scripts/staleness_benchmark.py` decides it: >=3/5 TP AND <=1/5 FP, pre-registered.

WHY KAGGLE. A 9B-14B reasoning model needs ~5-8 GB of weights; the local GPU has 4.0 GB, so it is CPU-only
here. A free Kaggle T4 has 16 GB and the work is BATCH-shaped (score N claims, emit JSON), which is exactly
what a queue-and-poll kernel is good for. It is NOT suited to in-the-loop review (no inbound endpoint).

WHAT THIS FILE IS. The kernel BODY is generated by `render_kernel()` and runs on Kaggle; everything else
here is pure and runs locally, so the prompt construction and the parsing are unit-testable without a GPU
and without network. `--emit-kernel` writes the notebook payload; `--score <results.json>` grades a
finished run against the benchmark.

HONEST SCOPE. A PASS means the model beat a deliberately low bar on 10 items. It would license running the
full corpus with every flag adjudicated against its artifact -- it would NOT license editing any doc on the
model's say-so. A FAIL closes the family and the negative gets recorded beside the mechanical screen's.

Run: uv run python scripts/kaggle_staleness_auditor.py --emit-kernel
     uv run python scripts/kaggle_staleness_auditor.py --score results.json
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

# A 9B-14B reasoning model that fits a 16 GB T4 with room for context.
DEFAULT_MODEL = "Qwen/Qwen3-8B"
ARTIFACT_HEAD_CHARS = 6000     # how much of the cited artifact to show the model


SYSTEM_PROMPT = """You audit documentation claims for STALENESS.

You are given a CLAIM made in a project's documentation, and an EXCERPT of the ARTIFACT that claim is
about. Decide whether the artifact still SUPPORTS the claim.

Answer exactly one of:
  stale     - the artifact CONTRADICTS the claim (e.g. the claim says work is "deferred"/"pending"/
              "blocked" but the artifact shows it was DONE, or the claim states a number/status the
              artifact disagrees with)
  supported - the artifact is consistent with the claim, OR the text merely MENTIONS a deferral that
              refers to something ELSE (a different sub-task), OR the text is itself a CORRECTION
              explaining that something was previously mis-stated
  unclear   - the excerpt genuinely does not settle it

CRITICAL: prose often mentions "deferred" or "pending" NEAR a file path without the claim being about that
file. Do not flag on keyword proximity. Flag only when the artifact's CONTENT contradicts the claim's
SUBSTANCE. A sentence that says "X was deferred, and here is the correction recording that it shipped" is
`supported` -- it is accurate text about a past error, not a stale claim.

Reply with STRICT JSON only, no prose outside it:
{"verdict": "stale|supported|unclear", "evidence": "<one sentence quoting what decided it>"}"""


def build_prompt(claim: str, artifact_path: str, artifact_text: str) -> str:
    """The user-turn prompt for one item. PURE -- no I/O, so it is testable without a GPU."""
    excerpt = artifact_text[:ARTIFACT_HEAD_CHARS]
    return (f"CLAIM (from project documentation):\n{claim}\n\n"
            f"ARTIFACT the claim is about: {artifact_path}\n"
            f"ARTIFACT EXCERPT:\n{excerpt}\n\n"
            f"Does the artifact still support the claim?")


_JSON = re.compile(r"\{[^{}]*\"verdict\"[^{}]*\}", re.S)
_VALID = ("stale", "supported", "unclear")


def parse_verdict(raw: str) -> dict:
    """Extract {verdict, evidence} from model output. PURE.

    FAIL-CLOSED to `unclear`: an unparseable answer must never be read as a flag. A parser that guessed
    `stale` on malformed output would manufacture true positives and corrupt the benchmark -- the
    scoring asymmetry (unclear counts as not-flagged) then makes a broken parser look like a cautious
    model rather than a bug.
    """
    if not raw:
        return {"verdict": "unclear", "evidence": "", "parse_ok": False}
    # a reasoning model may emit <think>...</think>; the answer is what follows
    raw = re.sub(r"<think>.*?</think>", " ", raw, flags=re.S)
    m = _JSON.search(raw)
    if not m:
        return {"verdict": "unclear", "evidence": raw.strip()[:200], "parse_ok": False}
    try:
        d = json.loads(m.group(0))
    except json.JSONDecodeError:
        return {"verdict": "unclear", "evidence": m.group(0)[:200], "parse_ok": False}
    v = str(d.get("verdict", "")).strip().lower()
    if v not in _VALID:
        return {"verdict": "unclear", "evidence": str(d.get("evidence", ""))[:200], "parse_ok": False}
    return {"verdict": v, "evidence": str(d.get("evidence", ""))[:300], "parse_ok": True}


def load_items_with_artifacts() -> list[dict]:
    """Benchmark items + the head of each cited artifact, ready to ship to the kernel."""
    from staleness_benchmark import build
    out = []
    for it in build():
        p = ROOT / it.artifact
        text = p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""
        out.append({"item_id": it.item_id, "claim": it.claim, "artifact": it.artifact,
                    "artifact_text": text[:ARTIFACT_HEAD_CHARS], "label": it.label})
    return out


def render_kernel(model: str = DEFAULT_MODEL) -> str:
    """The Kaggle kernel body. Reads items.json (uploaded as a dataset or inlined), writes results.json.

    Kaggle gotchas applied, all previously recorded in this repo: pin machine_shape NvidiaTeslaT4
    (`enable_gpu: true` alone provisions a P100 that current Kaggle torch cannot run in fp16); set
    PYTHONUTF8=1 or logs come back 0-byte; max 2 concurrent kernels.
    """
    # The items are INLINED rather than shipped as a dataset: 10 items is ~58 KB, well under any kernel
    # size limit, and it removes a whole failure mode (a dataset that did not attach leaves the kernel
    # reading a path that does not exist, which looks like a model failure rather than a plumbing one).
    items_json = json.dumps([{k: v for k, v in i.items() if k != "label"}
                             for i in load_items_with_artifacts()])
    return f'''import json, os, re, sys
os.environ.setdefault("PYTHONUTF8", "1")
import torch
from transformers import AutoTokenizer, AutoModelForCausalLM

MODEL = {model!r}
SYSTEM = """{SYSTEM_PROMPT}"""

items = json.loads({items_json!r})
print(f"loaded {{len(items)}} items", flush=True)
print("device:", torch.cuda.get_device_name(0) if torch.cuda.is_available() else "CPU", flush=True)

tok = AutoTokenizer.from_pretrained(MODEL)
model = AutoModelForCausalLM.from_pretrained(MODEL, torch_dtype=torch.bfloat16, device_map="auto")
model.eval()

out = []
for it in items:
    user = (f"CLAIM (from project documentation):\\n{{it['claim']}}\\n\\n"
            f"ARTIFACT the claim is about: {{it['artifact']}}\\n"
            f"ARTIFACT EXCERPT:\\n{{it['artifact_text']}}\\n\\n"
            f"Does the artifact still support the claim?")
    msgs = [{{"role": "system", "content": SYSTEM}}, {{"role": "user", "content": user}}]
    text = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
    ids = tok([text], return_tensors="pt").to(model.device)
    with torch.no_grad():
        gen = model.generate(**ids, max_new_tokens=1200, do_sample=False)
    raw = tok.decode(gen[0][ids.input_ids.shape[-1]:], skip_special_tokens=True)
    out.append({{"item_id": it["item_id"], "raw": raw}})
    print(f"{{it['item_id']}}: {{raw[:160]!r}}", flush=True)

json.dump(out, open("/kaggle/working/results.json", "w", encoding="utf-8"), indent=2)
print("wrote /kaggle/working/results.json", flush=True)
'''


def score_results(results_path: Path) -> dict:
    """Grade a finished kernel run against the pre-registered benchmark."""
    from staleness_benchmark import build, score, baseline_verdicts
    raw = json.loads(results_path.read_text(encoding="utf-8"))
    parsed = {r["item_id"]: parse_verdict(r.get("raw", "")) for r in raw}
    verdicts = {k: v["verdict"] for k, v in parsed.items()}
    items = build()
    s = score(items, verdicts)
    base = score(items, baseline_verdicts(items))
    return {
        "_schema": "staleness-auditor-result-v1",
        "model": DEFAULT_MODEL,
        "model_score": s.as_dict(),
        "mechanical_baseline": base.as_dict(),
        "beat_baseline": s.passed and not base.passed,
        "n_unparseable": sum(1 for v in parsed.values() if not v["parse_ok"]),
        "per_item": {k: {"verdict": v["verdict"], "evidence": v["evidence"],
                         "truth": next(i.label for i in items if i.item_id == k)}
                     for k, v in parsed.items()},
    }


def main() -> int:
    if "--emit-kernel" in sys.argv:
        items = load_items_with_artifacts()
        out_dir = ROOT / "scripts" / "kaggle"
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "staleness_items.json").write_text(
            json.dumps([{k: v for k, v in i.items() if k != "label"} for i in items], indent=2),
            encoding="utf-8")
        (out_dir / "staleness_auditor_kernel.py").write_text(render_kernel(), encoding="utf-8")
        missing = [i["item_id"] for i in items if not i["artifact_text"]]
        print(f"wrote {out_dir/'staleness_items.json'} ({len(items)} items)")
        print(f"wrote {out_dir/'staleness_auditor_kernel.py'}")
        if missing:
            print(f"WARNING: {len(missing)} items have an EMPTY artifact excerpt: {missing}")
            print("  (the model cannot judge an item it cannot see -- fix before running)")
        return 1 if missing else 0

    if "--score" in sys.argv:
        i = sys.argv.index("--score")
        res = score_results(Path(sys.argv[i + 1]))
        print(json.dumps(res, indent=2))
        return 0 if res["model_score"]["passed"] else 1

    print(__doc__)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
