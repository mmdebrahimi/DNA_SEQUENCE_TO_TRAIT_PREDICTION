def split_fingerprints() -> dict:
    """sha256 of each seed's held-out tile_indices, from the incumbents' committed tables.

    A hash proves exact ORDERED equality of the test set at ~32 bytes per seed, instead of shipping
    ~400 KB of tables to Kaggle just to compare them.
    """
    out = {}
    for s in range(10):
        p = TABLES / ("seed-%02d.json.gz" % s)
        with gzip.open(p, "rt", encoding="utf-8") as fh:
            d = json.load(fh)
        if d.get("smoke"):
            raise SystemExit("%s is a smoke table and cannot anchor a split" % p)
        if d["seed"] != s:
            raise SystemExit("%s declares seed %r" % (p, d["seed"]))
        idx = d["tile_indices"]
        out[str(s)] = {
            "sha": hashlib.sha256(",".join(str(i) for i in idx).encode()).hexdigest()[:32],
            "n_test": d["n_test"],
            "held_out_peaks": d["held_out_peaks"],
            "incumbent_spearman": {k: round(v, 4) for k, v in d["spearman_recomputed"].items()},
        }
    return out


