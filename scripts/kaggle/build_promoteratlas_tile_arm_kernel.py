NUC = {"A": 0, "C": 1, "G": 2, "T": 3}


def embed(model, seqs, width, device, batch=256):
    """Masked mean-pool of the final latent over the UNPADDED positions -> (N,128).

    width == len(seq) is the NATIVE geometry (primary). width > len(seq) zero-pads, which is how
    pretraining encoded a MASKED base -- measured to perturb the pooled embedding (max |delta| 1.232)
    even under masked pooling, because attention lets those columns reach the real positions. Run as
    the declared secondary cell so the geometry change is auditable.
    """
    import numpy as np, torch
    out = np.zeros((len(seqs), 128), dtype=np.float32)
    with torch.no_grad():
        for i in range(0, len(seqs), batch):
            chunk = seqs[i:i + batch]
            X = torch.zeros((len(chunk), 4, width))
            for b, s in enumerate(chunk):
                for j, c in enumerate(s):
                    k = NUC.get(c)
                    if k is not None:
                        X[b, k, j] = 1.0
            X = X.to(device)
            _, _, z = model(X, return_latent=True)
            L = len(chunk[0])
            out[i:i + len(chunk)] = z[:, :, :L].mean(dim=2).float().cpu().numpy()
            if i % (batch * 40) == 0:
                print("   embedded %d/%d (%.0fs)" % (i, len(seqs), time.time() - T0), flush=True)
    return out


def ridge_spearman(Xtr, ytr_raw, Xte, yte_raw, spearman, shuffle_seed=None):
    """Mirrors dna_decode.glm.expression.fit_predict_ridge EXACTLY: StandardScaler, Ridge(alpha=1.0),
    fit on log1p(expression), score Spearman against RAW expression. Any deviation makes the number
    incomparable with the committed incumbent tables, which is the whole point of the reconcile gate.
    """
    import numpy as np
    from sklearn.linear_model import Ridge
    from sklearn.preprocessing import StandardScaler
    ytr = np.log1p(np.asarray(ytr_raw, dtype=float))
    if shuffle_seed is not None:
        rng = np.random.default_rng(90_000 + shuffle_seed)
        ytr = ytr.copy()
        rng.shuffle(ytr)
    sc = StandardScaler().fit(Xtr)
    m = Ridge(alpha=ALPHA).fit(sc.transform(Xtr), ytr)
    pred = m.predict(sc.transform(Xte))
    return float(spearman(list(pred), list(yte_raw))), [float(v) for v in pred]


