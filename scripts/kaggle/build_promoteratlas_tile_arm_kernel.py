"""Build the Kaggle kernel for the PromoterAtlas frozen-embeddings ceiling arm.

WHY THIS EMBEDS SOURCES INSTEAD OF CLONING THE PROJECT REPO.

`fragment_pyramid_kernel.py` clones at a pinned SHA and argues, correctly, that a clone at a fixed
commit is as reproducible as an embedded tarball with far less machinery. That argument needs the
commit to EXIST on the remote. It does not here: origin/main sits at 655c26f8 and the working tree
is 13 commits ahead, including the acceptance bar this kernel implements. Pushing 13 commits is an
outward action nobody asked for, so this falls back to the OTHER documented pattern --
`build_glm_sampling_sweep_kernel.py` embeds sources precisely to stay version-exact against a
working tree newer than what is published. `dna_decode/glm/genomewide.py` imports only stdlib
(gzip, math, dataclasses, pathlib) and no project module, so embedding it costs exactly one file.

The PromoterAtlas repo IS cloned -- it is public, MIT, and third-party, so cloning it is a read of
someone else's published artifact rather than a push of ours.

SETTINGS THAT MATTER (set in the notebook; not inferable from the code):
  * Accelerator: GPU T4 x1. `enable_gpu` alone can provision a P100 (sm_60); the device report warns
    below CC 7.0. This arm is fp32 either way, so a P100 is slow-but-correct.
  * Internet: ON. Needed for the GitHub clone and the GEO download.
  * Free tier -> no money gate.

ORDER IS SMOKE THEN FULL. The smoke run is marked `smoke: true` and DELIBERATELY skips the
split-hash gate, because a subsampled tile pool cannot reproduce the full split -- so a smoke table
must never be scored. That mirrors `glm_tile_predictions.require_real`.

THE BUILDER VALIDATES THE EMITTED KERNEL, not just itself. On 2026-10-31 a builder that checked only
its own syntax shipped an unterminated string literal to Kaggle twice, because a collapsed escape
broke the EMITTED body. `ast.parse(body)` runs before the write and that check is proven non-vacuous
by `--self-test`.
"""
